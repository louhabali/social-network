export default function EmojiPicker( {onEmojiClick} ) {
    const [category, setCategory] = useState("faces");
    const emojisContainer = useRef(null);
    function handleEmojiClick(e) {
        if (e.target !== emojisContainer.current) {
            onEmojiClick(e.target.textContent);
        }
    }

    useEffect(() => {
        if (emojisContainer.current) emojisContainer.current.addEventListener("click", handleEmojiClick);
        return () => {
            if (emojisContainer.current) emojisContainer.current.removeEventListener("click", handleEmojiClick);
        }
    }, [])

    return (
        <div className={styles.picker}>
            <div className={styles.categories}>
                <span onClick={() => { if (category !== "faces") setCategory("faces") }}>
                    <FontAwesomeIcon
                        className={category == "faces" ? `${styles.icon} ${styles.selected}` : `${styles.icon}`}
                        icon={faFaceSmile}
                    />
                </span>
                <span onClick={() => { if (category !== "animals") setCategory("animals") }}>
                    <FontAwesomeIcon
                        className={category == "animals" ? `${styles.icon} ${styles.selected}` : `${styles.icon}`}
                        icon={faDog}
                    />
                </span>
                <span onClick={() => { if (category !== "food") setCategory("food") }}>
                    <FontAwesomeIcon
                        className={category == "food" ? `${styles.icon} ${styles.selected}` : `${styles.icon}`}
                        icon={faBowlFood}
                    />
                </span>
                <span onClick={() => { if (category !== "travel") setCategory("travel") }}>
                    <FontAwesomeIcon
                        className={category == "travel" ? `${styles.icon} ${styles.selected}` : `${styles.icon}`}
                        icon={faPlane}
                    />
                </span>
                <span onClick={() => { if (category !== "medal") setCategory("medal") }}>
                    <FontAwesomeIcon
                        className={category == "medal" ? `${styles.icon} ${styles.selected}` : `${styles.icon}`}
                        icon={faMedal}
                    />
                </span>
                <span onClick={() => { if (category !== "tools") setCategory("tools") }}>
                    <FontAwesomeIcon
                        className={category == "tools" ? `${styles.icon} ${styles.selected}` : `${styles.icon}`}
                        icon={faScrewdriverWrench}
                    />
                </span>
            </div>
            <div ref={emojisContainer} className={styles.emojis}>
                {
                    emojis[category].map((emoji, i) => <span className={styles.emoji} key={i}>{emoji}</span>)
                }
            </div>
        </div>
    )
}